export interface FieldPose {
  /** 场地米制。X∈[-14,14]，红方在 +X。 */
  x: number;
  y: number;
  /** 弧度，0=+X，逆时针。null = 位置可信但朝向没读到。 */
  yaw: number | null;
}

/**
 * 小地图归一化坐标 → 场地米制。
 *
 * 横轴翻转：小地图 u 增大对应场地 X 减小（红方=+X 画在小地图左侧）。
 * 纵轴同样翻转：小地图 v 向下增大，场地 Y 向上增大。
 */
export function minimapToField(
  u: number,
  v: number,
  kind: StreamKind = 'ground',
): { x: number; y: number } {
  const drone = kind === 'drone';
  const u0 = drone ? DRONE_MINIMAP_U0 : MINIMAP_U0;
  const v0 = drone ? DRONE_MINIMAP_V0 : MINIMAP_V0;
  const sx = drone ? DRONE_MINIMAP_SPAN_X : MINIMAP_SPAN_X;
  const sy = drone ? DRONE_MINIMAP_SPAN_Y : MINIMAP_SPAN_Y;
  return { x: (u0 - u) * sx, y: FIELD_CENTER_Y + (v0 - v) * sy };
}

/**
 * 小地图朝向 → 场地 yaw。
 *
 * 小地图朝向：0 = 正右（+u），顺时针为正（屏幕 y 向下）。
 * 场地 yaw：0 = +X，逆时针为正。
 *
 * 两个轴都翻了向，于是方向向量 (cosθ, sinθ) 在场地系里变成 (−cosθ, −sinθ)，
 * 即 **yaw = θ + π**。两次翻转把「顺时针 vs 逆时针」这一项也正好抵掉了，
 * 所以这里没有额外的取负 —— 这一点容易想当然地写错，改动前先回到这条推导。
 */
export function headingToYaw(heading: number): number {
  const y = heading + Math.PI;
  // 归一化到 (−π, π]，渲染侧按最短弧插值，跨越 ±π 时不该绕远路
  return y > Math.PI ? y - 2 * Math.PI : y;
}

/**
 * 把一次自机识别结果整体搬到场地系。
 * kind 决定用哪一组小地图常数 —— 空中机位画的是同一张地图但裁切不同，传错会系统性偏。
 *
 * 参数只要 x/y/heading：{@link SelfMarker} 的 radius/area 是检测的中间量，
 * 与坐标变换无关。这样 tracker 存下来的 Pose 也能直接喂进来，不必回头拼一个假的 marker。
 */
export function markerToField(
  m: Pick<SelfMarker, 'x' | 'y' | 'heading'>,
  kind: StreamKind = 'ground',
): FieldPose {
  const { x, y } = minimapToField(m.x, m.y, kind);
  return { x, y, yaw: m.heading === null ? null : headingToYaw(m.heading) };
}

/** 是否落在比赛场地内（不含木质底板外圈）。用于把明显离谱的解挡在沙盘之外。 */
export function insideField(x: number, y: number): boolean {
  return x >= FIELD_X[0] && x <= FIELD_X[1] && y >= FIELD_Y[0] && y <= FIELD_Y[1];
}
